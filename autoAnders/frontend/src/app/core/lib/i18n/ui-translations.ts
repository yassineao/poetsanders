const normalizedKeys = new Map(Object.keys(uiTranslations).map(key => [key.toLowerCase(), key]));

export function translateUi(value: string, locale: 'en' | 'nl' | 'de'): string {
  const display = value.replaceAll('_', ' ');
  const key = normalizedKeys.get(display.toLowerCase());
  const entry = key ? uiTranslations[key] : undefined;
  // Unknown values may be reference numbers or user content: preserve them exactly.
  return locale === 'en' ? value : entry?.[locale === 'nl' ? 0 : 1] ?? value;
}
