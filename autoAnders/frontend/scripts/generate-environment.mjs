import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from 'dotenv';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { parsed = {} } = config({ path: resolve(projectRoot, '.env'), quiet: true });
const envValue = (name) => process.env[name]?.trim() || parsed[name]?.trim() || '';
const outputPath = resolve(
  projectRoot,
  'src/environments/environment.generated.ts',
);
const apiBaseUrl = (
  envValue('API_BASE_URL') || envValue('VITE_API_URL') || 'https://autoanders-api.onrender.com'
).replace(/\/+$/, '');
const dealershipUrl = (
  envValue('DEALERSHIP_URL') || 'https://auto-anders.vercel.app'
).replace(/\/+$/, '');
const supabaseUrl = envValue('SUPABASE_URL').replace(/\/+$/, '');
const supabaseKey = envValue('SUPABASE_KEY');

const output = `// Generated by scripts/generate-environment.mjs.
export const environment = {
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  dealershipUrl: ${JSON.stringify(dealershipUrl)},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseKey: ${JSON.stringify(supabaseKey)},
} as const;
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output, 'utf8');
